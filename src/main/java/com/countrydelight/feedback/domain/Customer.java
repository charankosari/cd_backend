package com.countrydelight.feedback.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.SequenceGenerator;
import jakarta.persistence.Table;

import java.time.Instant;

/** A household. One app account = one household. The phone number is the login. */
@Entity
@Table(name = "customers")
public class Customer {

    /**
     * New signups get IDs from a database sequence starting at 100001.
     * Seeded demo households (101-110, 1001+) are inserted with fixed IDs by
     * CustomerRepository.insertWithId, so they never collide with the sequence.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "customer_seq")
    @SequenceGenerator(name = "customer_seq", sequenceName = "customer_seq", initialValue = 100001, allocationSize = 1)
    private Long id;

    @Column(nullable = false)
    private String name;

    @Column(nullable = false, unique = true, length = 10)
    private String phone;

    @Column(nullable = false)
    private String area;

    @Column(nullable = false)
    private String city;

    /** Only set on seeded demo users: describes which test scenario they cover. */
    @Column(length = 500)
    private String demoScenario;

    private Instant createdAt;

    protected Customer() {
    }

    /** Used by signup. The ID is generated by the database. */
    public Customer(String name, String phone, String area, String city, Instant createdAt) {
        this.name = name;
        this.phone = phone;
        this.area = area;
        this.city = city;
        this.createdAt = createdAt;
    }

    public Long getId() { return id; }
    public String getName() { return name; }
    public String getPhone() { return phone; }
    public String getArea() { return area; }
    public String getCity() { return city; }
    public String getDemoScenario() { return demoScenario; }
    public Instant getCreatedAt() { return createdAt; }
}
